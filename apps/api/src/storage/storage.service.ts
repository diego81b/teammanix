import { randomUUID } from 'node:crypto';
import { decrypt, encrypt, rewrap, type KeyRing } from './encryption';

/**
 * Private archive of sensitive files (medical certificates and, later, other documents of people).
 * The base class encrypts at rest with envelope encryption (see `encryption.ts`): the storage provider sees only opaque
 * bytes. Drivers only move raw bytes: `StorageFileSystem` (development) and `StorageS3` (production, any S3-compatible service).
 */
export abstract class StorageService {
  constructor(protected readonly ring: KeyRing) {}

  /** Returns the key to keep in the DB. */
  async save(clubId: string, data: Buffer): Promise<string> {
    const key = `${clubId}/${randomUUID()}`;
    validateKey(key); // also validates clubId
    await this.putRaw(key, encrypt(data, this.ring, key));
    return key;
  }

  async read(key: string): Promise<Buffer> {
    validateKey(key);
    return decrypt(await this.getRaw(key), this.ring, key);
  }

  /**
   * Moves the data key of one object to the current key without touching the file ciphertext. Returns false when the object is
   * already current. Unwraps the result before writing it, so a wrong key can never damage an object.
   */
  async rewrap(key: string, dryRun: boolean): Promise<boolean> {
    validateKey(key);
    const blob = await this.getRaw(key);
    const moved = rewrap(blob, this.ring, key);
    if (!moved) return false;
    if (!decrypt(moved, this.ring, key).equals(decrypt(blob, this.ring, key))) throw new Error('Rewrap verification failed');
    if (!dryRun) await this.putRaw(key, moved);
    return true;
  }

  /** Idempotent: an already missing file is not an error. */
  abstract remove(key: string): Promise<void>;
  /** Every stored object key, or only those of one club. */
  abstract listKeys(clubId?: string): AsyncIterable<string>;
  protected abstract getRaw(key: string): Promise<Buffer>;
  /** Creates or replaces the object. */
  protected abstract putRaw(key: string, blob: Buffer): Promise<void>;
}

const UUID = '[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}';
const FORMAT_KEY = new RegExp(`^${UUID}/${UUID}$`);

/** Keys are always `clubId/uuid`, generated by the server: anything else is an error, never a path. */
export function validateKey(key: string): void {
  if (!FORMAT_KEY.test(key)) throw new Error('Invalid storage key');
}

/** Rewraps every object. Stops on the first failure so a wrong key touches nothing; safe to repeat, converted objects are skipped. */
export async function rewrapAll(
  storage: StorageService,
  dryRun: boolean,
  clubId?: string,
): Promise<{ scanned: number; rewrapped: number }> {
  let scanned = 0;
  let rewrapped = 0;
  for await (const key of storage.listKeys(clubId)) {
    scanned++;
    try {
      if (await storage.rewrap(key, dryRun)) rewrapped++;
    } catch (e) {
      throw new Error(`Rewrap stopped at ${key}: ${e instanceof Error ? e.message : e}`);
    }
  }
  return { scanned, rewrapped };
}
