/**
 * Private archive of sensitive files (medical certificates and, later, other documents of people).
 * Implementations encrypt at rest with the application key: the storage provider sees only opaque bytes.
 * Drivers: `StorageFileSystem` (development) and `StorageS3` (production, any S3-compatible service).
 */
export abstract class StorageService {
  /** Returns the key to keep in the DB. */
  abstract save(clubId: string, data: Buffer): Promise<string>;
  abstract read(key: string): Promise<Buffer>;
  /** Idempotent: an already missing file is not an error. */
  abstract remove(key: string): Promise<void>;
}

const UUID = '[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}';
const FORMAT_KEY = new RegExp(`^${UUID}/${UUID}$`);

/** Keys are always `clubId/uuid`, generated by the server: anything else is an error, never a path. */
export function validateKey(key: string): void {
  if (!FORMAT_KEY.test(key)) throw new Error('Invalid storage key');
}
